"""Generate public/_redirects (Cloudflare static assets) from src/data/legacy.json.

Old WordPress URLs that no longer exist as pages get ONE 301 hop to their closest page.
Run: python3 scripts/build_redirects.py   (then commit public/_redirects)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
legacy = json.loads((ROOT / 'src/data/legacy.json').read_text())
ids = legacy['ids']

static: list[tuple[str, str]] = []
def add(old: str, new: str):
    static.append((old, new))

# 1. /category/<slug>/ → /<slug>/ (WordPress stripped the category base; old links may still use it)
for c in legacy['categories']:
    add(f"/category/{c['slug']}/", f"/{c['slug']}/" if c['count'] > 0 else '/')
add('/uncategorized/', '/')

# 2. Attachment pages → their parent post
for a in legacy['attachments']:
    parent = ids.get(str(a['parent']))
    add(a['attachment'], f'/{parent}/' if parent else '/')

# 3. Date archives and WordPress cruft
for d in ['/2010/10/', '/2010/11/', '/2011/09/', '/2011/12/', '/2012/05/', '/2010/', '/2011/', '/2012/', '/page/2/']:
    add(d, '/')
add('/sitemap.html', '/articles/')
for s in ['sitemap.xml', 'sitemap.xml.gz', 'sitemap-misc.xml', 'post_tag-sitemap.xml', 'category-sitemap.xml',
          'post-sitemap.xml', 'page-sitemap.xml', 'authors-sitemap.xml', 'archives-sitemap.xml']:
    static.append((f'/{s}', '/sitemap-index.xml'))
for f in ['/feed/', '/comments/feed/', '/rss/', '/atom/']:
    add(f, '/rss.xml')
# 4. Old slugs WordPress used to redirect (extend from the Redirection plugin export)
add('/drinking-water/', '/drinking-water-on-an-everest-base-camp-trek/')

lines = ['# Generated by scripts/build_redirects.py — do not edit by hand', '# Static rules (one 301 hop each)']
seen = set()
for old, new in static:
    for variant in {old, old.rstrip('/')} if old.endswith('/') and old != '/' else {old}:
        if variant in seen:
            continue
        seen.add(variant)
        lines.append(f'{variant} {new} 301')
lines += [
    '# Dynamic rules',
    '/:slug/feed/ /rss.xml 301',
    '/tag/:slug/feed/ /rss.xml 301',
    '/:slug/page/:n/ /:slug/ 301',
    '/tag/:slug/page/:n/ /tag/:slug/ 301',
]
out = ROOT / 'public/_redirects'
out.write_text('\n'.join(lines) + '\n')
n_static = sum(1 for l in lines if l and not l.startswith('#')) - 4
print(f'{out}: {n_static} static + 4 dynamic rules')
